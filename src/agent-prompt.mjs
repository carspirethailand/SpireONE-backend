/* Valet ปิดอยู่ แต่ผู้ใช้สั่งงานในแอป — ขึ้นการ์ด "อนุญาตและทำต่อ" ในแชต (กดครั้งเดียว ไม่ต้องพิมพ์ใหม่) ใช้ได้แค่คำสั่ง enable */
export const VALET_OFF = `

[ผู้ใช้สั่งให้ทำอะไรในแอป เช่น พาไปหน้า เปลี่ยนการตั้งค่า เพิ่มรถ เรียกช่าง ทักร้าน ขอราคา]
ตอบสั้น ๆ 1 ประโยคว่า Cendon Valet ทำเรื่องนี้ให้ได้เมื่อคุณกดอนุญาตในการ์ดด้านล่าง แล้วปิดท้ายด้วย [[ACT]]{"do":"enable"}[[/ACT]] (ห้ามใช้คำสั่งอื่น ห้ามแนะนำร้านหรือค้นหาร้านแทนการทำงาน)`;

/* ส่วนที่ต่อท้ายคำสั่งระบบของแชต: เปิด = รายการคำสั่ง · หน้าเว็บบอกว่าปิด = บอกทางเปิด · อื่น ๆ (LINE ฯลฯ) = ไม่มี */
export function valetPrompt(body) {
  const ctx = cleanAgent(body && body.agent);
  if (ctx) return valetBlock(ctx);
  return body && body.valet === false ? VALET_OFF : '';
}
